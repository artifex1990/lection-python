"""ASCII-графика виселицы."""

STAGES: tuple[str, ...] = (
    r"""
     +---+
     |   |
         |
         |
         |
    =====""",
    r"""
     +---+
     |   |
     O   |
         |
         |
    =====""",
    r"""
     +---+
     |   |
     O   |
     |   |
         |
    =====""",
    r"""
     +---+
     |   |
     O   |
    /|   |
         |
    =====""",
    r"""
     +---+
     |   |
     O   |
    /|\  |
         |
    =====""",
    r"""
     +---+
     |   |
     O   |
    /|\  |
    /    |
    =====""",
    r"""
     +---+
     |   |
     O   |
    /|\  |
    / \  |
    =====""",
)


def draw_gallows(mistakes: int) -> str:
    """Возвращает картинку виселицы для заданного числа ошибок."""
    index = min(mistakes, len(STAGES) - 1)
    return STAGES[index]
